use std::{
    fs::File,
    io::{BufWriter, Write},
    path::{Path, PathBuf},
};

use anyhow::{Context, Result, ensure};
use clap::Parser;
use multires::{
    LabelMeshOptions, MappedMsgArchive, Mesh3D, VertexRelaxOptions, mesh_labels,
    relax_mesh_vertices,
};

#[derive(Debug, Parser)]
#[command(about = "Enclose the union of exact labels from an MSG voxel field")]
struct Args {
    input: PathBuf,
    field: String,
    output: PathBuf,
    /// Label to include inside the mesh. Repeat to select a union.
    #[arg(long = "label", required = true, action = clap::ArgAction::Append)]
    labels: Vec<u16>,
    #[arg(long, default_value_t = 0)]
    level: usize,
    /// Number of bounded Taubin smoothing pass pairs; zero preserves voxel faces.
    #[arg(long, default_value_t = 3)]
    smooth_iterations: usize,
}

fn main() -> Result<()> {
    let args = Args::parse();
    let mapped = MappedMsgArchive::open(&args.input)?;
    let archive = mapped.view()?;
    let dataset = archive.decode_fields(&[&args.field])?;
    let mut mesh = mesh_labels(
        &dataset,
        &LabelMeshOptions {
            field: args.field,
            labels: args.labels,
            level: args.level,
        },
    )?;
    if args.smooth_iterations != 0 {
        relax_mesh_vertices(
            &mut mesh,
            VertexRelaxOptions {
                iterations: args.smooth_iterations,
                ..VertexRelaxOptions::default()
            },
        )?;
    }
    ensure!(
        !mesh.indices.is_empty(),
        "selected labels produced an empty mesh"
    );
    write_obj(&args.output, &mesh)?;
    eprintln!(
        "wrote {} vertices and {} faces to {}",
        mesh.positions.len(),
        mesh.indices.len(),
        args.output.display()
    );
    Ok(())
}

fn write_obj(path: &Path, mesh: &Mesh3D) -> Result<()> {
    let mut output =
        BufWriter::new(File::create(path).with_context(|| format!("creating {}", path.display()))?);
    writeln!(output, "# generated by msg-label-surface")?;
    for position in &mesh.positions {
        writeln!(output, "v {} {} {}", position[0], position[1], position[2])?;
    }
    for face in &mesh.indices {
        let indices = face.map(|index| u64::from(index) + 1);
        writeln!(output, "f {} {} {}", indices[0], indices[1], indices[2])?;
    }
    output.flush()?;
    Ok(())
}
